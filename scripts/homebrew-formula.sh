#!/bin/bash
# Write the Homebrew formula for a release, from its SHA256SUMS.
#
#   scripts/homebrew-formula.sh 0.1.0 > Formula/kalonide.rb
#
# The formula installs the prebuilt binary for the machine (macOS or
# Linux, ARM or Intel) from the GitHub release. It belongs in the tap
# repository KalonEdge/homebrew-tap, so users run:
#   brew install kalonedge/tap/kalonide
set -euo pipefail

VERSION="${1:?usage: $0 <version>}"
cd "$(dirname "$0")/.."
SUMS="dist/$VERSION/SHA256SUMS"
[[ -f "$SUMS" ]] || { echo "no $SUMS; run scripts/release.sh $VERSION first" >&2; exit 1; }
BASE="https://github.com/KalonEdge/kalonide/releases/download/v$VERSION"

sha() {
	local f="kalonide_${VERSION}_$1.tar.gz"
	local s
	s="$(awk -v f="$f" '$2 == f { print $1 }' "$SUMS")"
	[[ -n "$s" ]] || { echo "$f is missing from $SUMS" >&2; exit 1; }
	echo "$s"
}

cat <<EOF
# Generated by scripts/homebrew-formula.sh for Kalonide $VERSION.
class Kalonide < Formula
  desc "Coding agent for the terminal, for Kalon and OpenAI-compatible model servers"
  homepage "https://github.com/KalonEdge/kalonide"
  license "MIT"

  on_macos do
    on_arm do
      url "$BASE/kalonide_${VERSION}_darwin_arm64.tar.gz"
      sha256 "$(sha darwin_arm64)"
    end
    on_intel do
      url "$BASE/kalonide_${VERSION}_darwin_amd64.tar.gz"
      sha256 "$(sha darwin_amd64)"
    end
  end

  on_linux do
    on_arm do
      url "$BASE/kalonide_${VERSION}_linux_arm64.tar.gz"
      sha256 "$(sha linux_arm64)"
    end
    on_intel do
      url "$BASE/kalonide_${VERSION}_linux_amd64.tar.gz"
      sha256 "$(sha linux_amd64)"
    end
  end

  def install
    bin.install "kalonide"
  end

  test do
    assert_match "kalonide #{version}", shell_output("#{bin}/kalonide --version")
  end
end
EOF
